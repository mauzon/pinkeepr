#!/usr/bin/env node
/**
 * Generate migrations/seed/seed.sql from local D1 (after d1:seed). Do not commit real trip data.
 */
import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { d1DatabaseName, d1WranglerConfigPath } from "./lib/d1-wrangler-config.mjs";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const wranglerConfig = d1WranglerConfigPath(root);
const dbName = d1DatabaseName(root);
const outDir = path.join(root, "migrations/seed");
const outFile = path.join(outDir, "seed.sql");
fs.mkdirSync(outDir, { recursive: true });

execSync(
  `npx wrangler d1 export ${dbName} --local --no-schema --output "${outFile}" -y -c "${wranglerConfig}"`,
  { cwd: root, stdio: "inherit" },
);

const header = `-- Generated by scripts/generate-seed-sql.mjs — run AFTER migrations 0001–0003.\n-- Apply: wrangler d1 execute ${dbName} --remote --file=migrations/seed/seed.sql -c wrangler.d1.jsonc\n\n`;
const body = fs.readFileSync(outFile, "utf8");
fs.writeFileSync(outFile, header + body.trimStart());
console.log(`wrote ${outFile}`);